import AppKit
import ApplicationServices
import Carbon.HIToolbox
import os

/// Puts dictated text at the text cursor of the frontmost app.
///
/// Default: swap the clipboard, synthesize ⌘V, restore the clipboard. That works almost
/// everywhere (native, Electron, browsers, terminals). Alternatives for apps where
/// pasting misbehaves: typing the characters, or setting the focused element's selected
/// text through the Accessibility API. All three need the Accessibility permission.
enum TextInserter {
    enum Method: String, CaseIterable, Identifiable {
        case paste, type, accessibility
        var id: String { rawValue }
        var title: String {
            switch self {
            case .paste: "Paste (recommended)"
            case .type: "Type characters"
            case .accessibility: "Accessibility API"
            }
        }
    }

    enum Failure: Error, LocalizedError {
        case notTrusted
        case secureInput
        case accessibilityRejected(AXError)

        var errorDescription: String? {
            switch self {
            case .notTrusted: "Murmur needs Accessibility access to type into other apps."
            case .secureInput: "A password field or secure terminal is blocking typed input. The text is in Murmur's menu."
            case .accessibilityRejected(let e): "The app didn't accept the text (AX error \(e.rawValue))."
            }
        }
    }

    static let methodKey = "insertionMethod"
    static var method: Method {
        UserDefaults.standard.string(forKey: methodKey).flatMap(Method.init) ?? .paste
    }

    private static let log = Logger(subsystem: "io.github.garfield-oo7.Murmur", category: "insert")

    static func insert(_ text: String) async throws {
        guard AXIsProcessTrusted() else { throw Failure.notTrusted }
        // Secure Event Input (password fields, Terminal's Secure Keyboard Entry) drops
        // synthesized key events, so paste and typing would silently do nothing.
        guard !IsSecureEventInputEnabled() else { throw Failure.secureInput }

        await waitForModifierRelease()
        let text = withLeadingSpaceIfNeeded(text)
        let app = NSWorkspace.shared.frontmostApplication?.localizedName ?? "?"

        switch method {
        case .paste:
            await paste(text)
        case .type:
            await type(text)
        case .accessibility:
            do {
                try setSelectedText(text)
            } catch {
                log.notice("AX insert failed in \(app, privacy: .public) (\(error, privacy: .public)); pasting instead")
                await paste(text)
            }
        }
        log.notice("inserted \(text.count) chars into \(app, privacy: .public) via \(method.rawValue, privacy: .public)")
    }

    // MARK: Paste

    private static func paste(_ text: String) async {
        let pasteboard = NSPasteboard.general
        let saved = snapshot(pasteboard)

        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        // nspasteboard.org conventions: clipboard managers skip transient items.
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pasteboard.writeObjects([item])
        let ourChange = pasteboard.changeCount

        postKey(keyCode(for: "v") ?? CGKeyCode(kVK_ANSI_V), flags: .maskCommand)

        // Apps read the pasteboard when they handle ⌘V, sometimes a little later
        // (Electron). Restore afterwards, unless something else has been copied since.
        try? await Task.sleep(for: .milliseconds(400))
        if pasteboard.changeCount == ourChange {
            restore(saved, to: pasteboard)
        }
    }

    private typealias Snapshot = [[(NSPasteboard.PasteboardType, Data)]]

    private static func snapshot(_ pasteboard: NSPasteboard) -> Snapshot {
        (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in item.data(forType: type).map { (type, $0) } }
        }
    }

    private static func restore(_ snapshot: Snapshot, to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        guard !snapshot.isEmpty else { return }
        pasteboard.writeObjects(snapshot.map { entries in
            let item = NSPasteboardItem()
            for (type, data) in entries { item.setData(data, forType: type) }
            return item
        })
    }

    // MARK: Typing

    private static func type(_ text: String) async {
        let source = CGEventSource(stateID: .privateState)
        let units = Array(text.utf16)
        // Some apps truncate long unicode strings per event; ~20 UTF-16 units is safe.
        var start = 0
        while start < units.count {
            var end = min(start + 20, units.count)
            // Don't split a surrogate pair.
            if end < units.count, UTF16.isTrailSurrogate(units[end]) { end -= 1 }
            let chunk = Array(units[start..<end])
            for down in [true, false] {
                let event = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: down)
                event?.flags = []
                event?.keyboardSetUnicodeString(stringLength: chunk.count, unicodeString: chunk)
                event?.post(tap: .cghidEventTap)
            }
            start = end
            try? await Task.sleep(for: .milliseconds(5))
        }
    }

    // MARK: Accessibility

    private static func focusedElement() -> AXUIElement? {
        let system = AXUIElementCreateSystemWide()
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &value) == .success,
              let value, CFGetTypeID(value) == AXUIElementGetTypeID() else { return nil }
        return (value as! AXUIElement)
    }

    private static func setSelectedText(_ text: String) throws {
        guard let element = focusedElement() else { throw Failure.accessibilityRejected(.noValue) }
        let result = AXUIElementSetAttributeValue(element, kAXSelectedTextAttribute as CFString, text as CFTypeRef)
        guard result == .success else { throw Failure.accessibilityRejected(result) }
    }

    /// Adds a space when the caret sits right after a word, so consecutive dictations
    /// don't run together. Best effort: only when the app exposes its text via AX.
    private static func withLeadingSpaceIfNeeded(_ text: String) -> String {
        guard let first = text.unicodeScalars.first,
              !CharacterSet.punctuationCharacters.contains(first),
              let element = focusedElement() else { return text }

        var rangeValue: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXSelectedTextRangeAttribute as CFString, &rangeValue) == .success,
              let rangeValue, CFGetTypeID(rangeValue) == AXValueGetTypeID() else { return text }
        var selection = CFRange()
        guard AXValueGetValue(rangeValue as! AXValue, .cfRange, &selection), selection.location > 0 else { return text }

        var previous = CFRange(location: selection.location - 1, length: 1)
        guard let previousValue = AXValueCreate(.cfRange, &previous) else { return text }
        var charValue: CFTypeRef?
        guard AXUIElementCopyParameterizedAttributeValue(element, kAXStringForRangeParameterizedAttribute as CFString,
                                                         previousValue, &charValue) == .success,
              let before = (charValue as? String)?.unicodeScalars.first else { return text }
        let needsSpace = !CharacterSet.whitespacesAndNewlines.contains(before) && !"([{\"'“‘/".unicodeScalars.contains(before)
        return needsSpace ? " " + text : text
    }

    /// Self-test only: the focused element's full text, to check what landed.
    static func focusedTextForTesting() -> String? {
        guard let element = focusedElement() else { return nil }
        var value: CFTypeRef?
        AXUIElementCopyAttributeValue(element, kAXValueAttribute as CFString, &value)
        return value as? String
    }

    // MARK: Keyboard helpers

    /// The hotkey's modifiers (e.g. Option) may still be down when the transcript is
    /// ready, which would turn ⌘V into ⌥⌘V. Wait briefly for them to be released.
    private static func waitForModifierRelease() async {
        let modifiers: CGEventFlags = [.maskAlternate, .maskControl, .maskShift, .maskCommand]
        let deadline = ContinuousClock.now + .seconds(1)
        while ContinuousClock.now < deadline,
              !CGEventSource.flagsState(.combinedSessionState).intersection(modifiers).isEmpty {
            try? await Task.sleep(for: .milliseconds(10))
        }
    }

    private static func postKey(_ keyCode: CGKeyCode, flags: CGEventFlags) {
        // A private source keeps physically held keys out of the synthesized event.
        let source = CGEventSource(stateID: .privateState)
        for down in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: down)
            event?.flags = flags
            event?.post(tap: .cghidEventTap)
        }
    }

    /// Virtual key code that produces `character` in the current keyboard layout, so ⌘V
    /// still means paste on Dvorak, AZERTY and friends.
    private static func keyCode(for character: Character) -> CGKeyCode? {
        let target = String(character)
        for code in 0..<128 where Shortcut.keyName(UInt32(code)).lowercased() == target {
            return CGKeyCode(code)
        }
        return nil
    }
}
